function toggleMiniPlayer() {
  if (NoorApp.audioPlaying) {
    if (NoorApp.currentAudio) NoorApp.currentAudio.pause();
    NoorApp.audioPlaying = false;
    const btn = $('#mp-play-btn');
    if (btn) btn.textContent = '▶';
  } else {
    if (NoorApp.currentAudio) NoorApp.currentAudio.play().catch(()=>{});
    NoorApp.audioPlaying = true;
    const btn = $('#mp-play-btn');
    if (btn) btn.textContent = '⏸';
  }
}

function setVolume(val) {
  if (NoorApp.currentAudio) NoorApp.currentAudio.volume = val / 100;
}

