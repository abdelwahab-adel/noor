async function loadDailyAyah() {
  const el = $('#daily-ayah-text');
  const srcEl = $('#daily-ayah-source');
  if (!el) return;

  // Use day-based number
  const ayahNum = (new Date().getDate() * 37 + new Date().getMonth() * 91) % 6236 + 1;

  try {
    const res = await fetch(`${NOOR_CONFIG.QURAN_API}/ayah/${ayahNum}/quran-uthmani`);
    const data = await res.json();
    if (data.code === 200) {
      html(el, data.data.text);
      if (srcEl) html(srcEl, `سورة ${data.data.surah.name} — الآية ${data.data.numberInSurah}`);
    }
  } catch(e) {
    html(el, 'بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ');
    if (srcEl) html(srcEl, 'سورة الفاتحة — الآية ١');
  }
}

