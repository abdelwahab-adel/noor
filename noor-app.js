function navigateTo(section) {
  NoorApp.currentSection = section;

  // Update nav links
  $$('.nav-link').forEach(l => {
    l.classList.toggle('active', l.dataset.section === section);
  });

  // Show/hide sections
  $$('.noor-section').forEach(s => {
    s.classList.toggle('active', s.id === `section-${section}`);
  });

  // Close mobile menu
  const mMenu = $('#mobile-menu');
  const burger = $('.nav-hamburger');
  if (mMenu) mMenu.classList.remove('open');
  if (burger) burger.classList.remove('open');

  // Scroll to top
  window.scrollTo({ top: 0, behavior: 'smooth' });

  // Load section-specific content
  switch(section) {
    case 'home': renderHome(); break;
    case 'quran': renderQuranList(); break;
    case 'seerah': renderTimeline(); break;
    case 'ghazawat': renderGhazawat(); break;
    case 'sahaba': renderSahaba(); break;
    case 'azkar': renderAzkar(); break;
    case 'stories': renderStories(); break;
    case 'radio': renderRadio(); break;
    case 'asma': renderAsma(); break;
    case 'search': renderSearch(); break;
  }
}

