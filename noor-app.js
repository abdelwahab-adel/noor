function shareContent(text, title = 'نُور — المنصة الإسلامية') {
  if (navigator.share) {
    navigator.share({ title, text, url: window.location.href });
  } else {
    navigator.clipboard.writeText(text).then(() => showToast('تم نسخ النص'));
  }
}

