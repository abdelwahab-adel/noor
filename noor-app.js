async function openSurah(num) {
  const surah = NoorApp.surahs.find(s => s.number === num);
  if (!surah) return;
  NoorApp.selectedSurah = surah;

  // Show reader view
  const list = $('#quran-list-view');
  const reader = $('#quran-reader-view');
  if (list) hide(list);
  if (reader) show(reader);

  // Update header
  const nameEl = $('#reader-surah-name');
  const metaEl = $('#reader-surah-meta');
  if (nameEl) html(nameEl, surah.name);
  if (metaEl) html(metaEl, `
    <span>${surah.numberOfAyahs} آية</span>
    <span>•</span>
    <span>${surah.revelationType === 'Meccan' ? 'مكية' : 'مدنية'}</span>
    <span>•</span>
    <span>ترتيب: ${surah.number}</span>
  `);

  // Load ayahs
  const ayahsContainer = $('#ayahs-container');
  if (ayahsContainer) html(ayahsContainer, `
    <div style="text-align:center;padding:3rem;color:var(--text-muted)">
      <div style="font-size:2rem;margin-bottom:1rem;animation:loadingSpin 1.5s ease infinite">📖</div>
      <p>جاري تحميل الآيات الكريمة...</p>
    </div>
  `);

  // Set audio
  const audioEl = $('#surah-audio');
  const numStr = num.toString().padStart(3, '0');
  if (audioEl) {
    audioEl.src = `${NOOR_CONFIG.AUDIO_BASE}${numStr}.mp3`;
    audioEl.load();
  }

  try {
    const res = await fetch(`${NOOR_CONFIG.QURAN_API}/surah/${num}/editions/quran-uthmani,en.sahih`);
    const data = await res.json();
    const arabicAyahs = data.data[0].ayahs;
    const transAyahs = data.data[1].ayahs;
    NoorApp.ayahs = arabicAyahs.map((a, i) => ({ ...a, translation: transAyahs[i].text }));
    renderAyahs();
  } catch(e) {
    if (ayahsContainer) html(ayahsContainer, `
      <div style="text-align:center;padding:3rem;color:var(--text-muted)">
        <p>تعذّر تحميل الآيات. يرجى التحقق من الاتصال بالإنترنت.</p>
      </div>
    `);
  }
}

function renderAyahs() {
  const container = $('#ayahs-container');
  if (!container || !NoorApp.ayahs.length) return;

  const surahNum = NoorApp.selectedSurah?.number;
  const bismillah = surahNum && surahNum !== 1 && surahNum !== 9
    ? `<div class="bismillah">بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ</div>` : '';

  const strip = (text) => {
    if (!surahNum || surahNum === 1 || surahNum === 9) return text;
    const variants = ['بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ','بِسْمِ اللَّهِ الرَّحْمَنِ الرَّحِيمِ','بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ الرَّحِيمِ'];
    for (const v of variants) if (text.startsWith(v)) return text.slice(v.length).trim();
    return text;
  };

  container.innerHTML = bismillah + NoorApp.ayahs.map((a, i) => `
    <div class="ayah-item">
      <p class="ayah-text" style="font-size:${NoorApp.fontSize}px">
        <span class="ayah-num-badge">${a.numberInSurah}</span>
        ${i === 0 ? strip(a.text) : a.text}
        <span style="color:var(--gold);font-size:0.7em"> ۝${a.numberInSurah}</span>
      </p>
      ${NoorApp.showTranslation ? `<p class="ayah-translation">${a.translation}</p>` : ''}
    </div>
  `).join('');
}

