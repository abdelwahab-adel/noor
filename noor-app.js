async function loadPrayerTimes() {
  try {
    // Try geolocation first
    let city = NOOR_CONFIG.DEFAULT_CITY, country = NOOR_CONFIG.DEFAULT_COUNTRY;
    const url = `${NOOR_CONFIG.PRAYER_API}/timingsByCity?city=${encodeURIComponent(city)}&country=${encodeURIComponent(country)}&method=4`;
    const res = await fetch(url);
    const data = await res.json();
    if (data.code === 200) {
      NoorApp.prayerTimes = data.data.timings;
      renderPrayerWidget();
    }
  } catch(e) {
    console.log('Prayer API unavailable, using fallback');
    // Fallback mock times
    NoorApp.prayerTimes = { Fajr:'05:15', Dhuhr:'12:30', Asr:'15:45', Maghrib:'18:20', Isha:'19:45' };
    renderPrayerWidget();
  }
}

