function playStation(station) {
  if (typeof station === 'string') station = JSON.parse(station.replace(/&quot;/g,'"'));
  if (NoorApp.currentStation?.id === station.id && NoorApp.audioPlaying) {
    stopRadio();
    return;
  }

  NoorApp.currentStation = station;
  NoorApp.audioPlaying = true;

  if (!NoorApp.currentAudio) {
    NoorApp.currentAudio = new Audio();
    NoorApp.currentAudio.addEventListener('error', () => showToast('تعذّر الاتصال بالمحطة'));
  }

  NoorApp.currentAudio.src = station.url;
  NoorApp.currentAudio.volume = 0.8;
  NoorApp.currentAudio.play().catch(() => showToast('تعذّر تشغيل البث المباشر'));

  // Update mini player
  showMiniPlayer(station);
  renderRadio($('#radio-search-input')?.value || '', $('#radio-cat-select')?.value || '');
}

function stopRadio() {
  if (NoorApp.currentAudio) {
    NoorApp.currentAudio.pause();
    NoorApp.currentAudio.src = '';
  }
  NoorApp.currentStation = null;
  NoorApp.audioPlaying = false;
  hideMiniPlayer();
  renderRadio($('#radio-search-input')?.value || '', $('#radio-cat-select')?.value || '');
}

