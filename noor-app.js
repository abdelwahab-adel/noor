function renderSearch() {
  const input = $('#search-input');
  if (input && NoorApp.searchQuery) {
    input.value = NoorApp.searchQuery;
    doSearch(NoorApp.searchQuery);
  }
}

function doSearch(q) {
  const results = $('#search-results');
  if (!results || !q.trim()) {
    if (results) html(results, '');
    return;
  }

  NoorApp.searchQuery = q;
  const items = [];

  // Search Timeline
  NOOR_TIMELINE.forEach((t,i) => {
    if (t.title.includes(q) || t.desc.includes(q) || t.era.includes(q))
      items.push({ type:'السيرة النبوية', title:t.title, snippet:t.desc.substring(0,100), action:`navigateTo('seerah')` });
  });

  // Search Ghazawat
  NOOR_GHAZAWAT.forEach((g,i) => {
    if (g.name.includes(q) || g.reason.includes(q) || g.result.includes(q))
      items.push({ type:'الغزوات', title:g.name, snippet:g.reason.substring(0,100), action:`navigateTo('ghazawat')` });
  });

  // Search Sahaba
  NOOR_SAHABA.forEach((s,i) => {
    if (s.name.includes(q) || s.desc.includes(q) || s.badge.includes(q))
      items.push({ type:'الصحابة', title:s.name, snippet:s.desc.substring(0,100), action:`navigateTo('sahaba')` });
  });

  // Search Stories
  NOOR_STORIES.forEach((s,i) => {
    if (s.name.includes(q) || s.content.includes(q) || s.summary.includes(q))
      items.push({ type:'قصص الأنبياء', title:s.name, snippet:s.summary, action:`openStory(${i});navigateTo('stories')` });
  });

  // Search Stations
  NOOR_STATIONS.forEach(s => {
    if (s.name.includes(q) || s.cat.includes(q))
      items.push({ type:'الإذاعة', title:s.name, snippet:s.cat, action:`navigateTo('radio')` });
  });

  // Search Asma
  NOOR_ASMA.forEach((a,i) => {
    if (a.ar.includes(q) || a.meaning.includes(q))
      items.push({ type:'أسماء الله الحسنى', title:a.ar, snippet:a.meaning.substring(0,100), action:`navigateTo('asma')` });
  });

  if (items.length === 0) {
    html(results, `<div style="text-align:center;padding:3rem;color:var(--text-muted)">
      <div style="font-size:3rem;margin-bottom:1rem">🔍</div>
      <p>لا توجد نتائج مطابقة لـ "${q}"</p>
      <p style="font-size:0.85rem;margin-top:0.5rem">جرب كلمات مختلفة</p>
    </div>`);
    return;
  }

  html(results, items.slice(0,20).map(item => `
    <div class="search-result-item" onclick="${item.action}">
      <div class="search-result-type">${item.type}</div>
      <div class="search-result-title">${item.title}</div>
      <div class="search-result-snippet">${item.snippet}...</div>
    </div>
  `).join(''));
}

